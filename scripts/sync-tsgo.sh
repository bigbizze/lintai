#!/usr/bin/env bash
# Copies the Go packages of the TypeScript 7 compiler that
# internal/tsgo/lintaiapi needs into internal/tsgo/internal/, from one
# microsoft/TypeScript commit. Nothing else writes to internal/tsgo/internal/.
#
# Usage: scripts/sync-tsgo.sh <commit>
set -euo pipefail

if [ $# -ne 1 ] || ! [[ "$1" =~ ^[0-9a-f]{40}$ ]]; then
	echo "usage: scripts/sync-tsgo.sh <40-character microsoft/TypeScript commit>" >&2
	exit 2
fi
commit="$1"
repo_root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$repo_root"

upstream_prefix="github.com/microsoft/TypeScript/tsc/"
local_prefix="github.com/bigbizze/lintai/internal/tsgo/"
dest="internal/tsgo/internal"

work="$(mktemp -d)"
trap 'chmod -R u+w "$work" 2>/dev/null; find "$work" -delete 2>/dev/null' EXIT

rewrite="$work/tsgo-rewrite-imports"
go build -o "$rewrite" ./scripts/tsgo-rewrite-imports

# 1. Fetch the commit: tsc/ and the top-level license files only.
src="$work/TypeScript"
git init -q "$src"
git -C "$src" remote add origin https://github.com/microsoft/TypeScript.git
git -C "$src" sparse-checkout set --no-cone /tsc/ /LICENSE.txt /NOTICE.txt >/dev/null
git -C "$src" fetch -q --depth 1 --filter=blob:none origin "$commit"
git -C "$src" -c advice.detachedHead=false checkout -q FETCH_HEAD
commit_date="$(git -C "$src" log -1 --format=%cI FETCH_HEAD)"
tsc="$src/tsc"

# 2. Compute the closure of lintaiapi inside the fetched module, for every
# operating system lintai builds on.
probe="$tsc/lintaisyncprobe"
mkdir "$probe"
for file in internal/tsgo/lintaiapi/*.go; do
	case "$file" in *_test.go) continue ;; esac
	cp "$file" "$probe/"
done
"$rewrite" -from "$local_prefix" -to "$upstream_prefix" "$probe"/*.go
(cd "$tsc" && go mod download)
deps="$(
	cd "$tsc"
	for goos in linux darwin windows; do
		GOOS="$goos" go list -deps -f '{{.ImportPath}}' ./lintaisyncprobe
	done | sort -u
)"
outside="$(printf '%s\n' "$deps" | grep "^${upstream_prefix}" | grep -v "^${upstream_prefix}internal/" | grep -v "^${upstream_prefix}lintaisyncprobe$" || true)"
if [ -n "$outside" ]; then
	echo "lintaiapi imports compiler packages outside internal/:" >&2
	echo "$outside" >&2
	exit 1
fi
packages="$(printf '%s\n' "$deps" | grep "^${upstream_prefix}internal/" | sed "s|^${upstream_prefix}||")"

# 3. Replace internal/tsgo/internal/ with the closure. Files for every
# operating system are kept; build constraints select them.
if [ -d "$dest" ]; then
	find "$dest" -delete
fi
for pkg in $packages; do
	mkdir -p "$dest/${pkg#internal/}"
	for file in "$tsc/$pkg"/*.go; do
		case "$file" in *_test.go) continue ;; esac
		if head -n 1 "$file" | grep -qE '^//go:build (ignore|generate)$'; then
			continue
		fi
		cp "$file" "$dest/${pkg#internal/}/"
	done
	embeds="$(cd "$tsc" && go list -f '{{range .EmbedFiles}}{{println .}}{{end}}' "./$pkg")"
	for embed in $embeds; do
		mkdir -p "$dest/${pkg#internal/}/$(dirname "$embed")"
		cp "$tsc/$pkg/$embed" "$dest/${pkg#internal/}/$embed"
	done
done
find "$dest" -type f -exec chmod 644 {} +

# 4. Apply lintai's patches, if any.
for patch in internal/tsgo/patches/*.patch; do
	[ -e "$patch" ] || continue
	git apply --directory="$dest" "$patch"
done

# 5 and 6. Rewrite import paths and mark the copied files as generated.
find "$dest" -name '*.go' -print0 | sort -z | xargs -0 "$rewrite" \
	-from "$upstream_prefix" -to "$local_prefix" -base "$dest/" \
	-header "Code generated by scripts/sync-tsgo.sh from microsoft/TypeScript tsc/internal/{path} at $commit. DO NOT EDIT."
"$rewrite" -from "$upstream_prefix" -to "$local_prefix" internal/tsgo/lintaiapi/*.go

# 7. License and notices.
cp "$src/LICENSE.txt" internal/tsgo/LICENSE.txt
cp "$src/NOTICE.txt" internal/tsgo/NOTICE.txt
chmod 644 internal/tsgo/LICENSE.txt internal/tsgo/NOTICE.txt

# 8. VERSION.
core_version="$(sed -n 's/^var version = "\(.*\)"$/\1/p' "$tsc/internal/core/version.go")"
npm_version=""
if [ -n "$core_version" ]; then
	command -v npm >/dev/null || { echo "sync-tsgo: npm is required to look up typescript@$core_version" >&2; exit 1; }
	npm_err="$work/npm-view.err"
	npm_status=0
	npm_head="$(npm view "typescript@$core_version" gitHead 2>"$npm_err")" || npm_status=$?
	if [ "$npm_status" -ne 0 ] && ! grep -q E404 "$npm_err"; then
		echo "sync-tsgo: npm view typescript@$core_version failed:" >&2
		cat "$npm_err" >&2
		exit 1
	fi
	if [ "$npm_head" = "$commit" ]; then
		npm_version="$core_version"
	fi
fi
{
	echo "commit: $commit"
	echo "date: $commit_date"
	echo "npm: ${npm_version:-none}"
	echo "packages: $(printf '%s\n' "$packages" | wc -l | tr -d ' ')"
} >internal/tsgo/VERSION

# 9. Module requirements and build.
go mod tidy
go build ./...
echo "synced $(printf '%s\n' "$packages" | wc -l | tr -d ' ') packages from microsoft/TypeScript $commit"
